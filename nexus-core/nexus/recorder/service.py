"""Single-active-capture orchestration above the durable recorder store (plan 54, B2).

The service owns the one mutable thing the storage layer deliberately does not: *who may append audio*.
One recording at a time may have a capture lease (opaque bearer token plus a `stream_id`/`client_id`
binding). Chunk commits, heartbeats and stops are serialized here, then delegated to
:class:`nexus.recorder.store.RecorderStore`, so a stop/upload race cannot interleave inside a chunk
commit. Storage remains authoritative for the durable sample range, hashes and recovery.

Security properties:

* A lease token is generated with :func:`secrets.token_urlsafe`, compared in constant time and never
  published in an event or snapshot. The recovery capability is generated by the client and persisted by
  it before the create call; Core stores only its sha256 in the same atomic `meta.json` as the recording
  identity, so a crash after `store.create` but before the service sidecar still replays the same
  recording. The private `lease.json` sidecar adds stop intent, revision and pending state-outbox data.
  Raw capabilities and idempotency keys are never written to disk. `create` never generates, stores or
  returns a recovery token. A replay must prove possession of the same client capability: while its lease
  is still active that proof reissues only the lease; otherwise the replay returns an explicit
  `replay_state`/`recoverable` response with no tokens reissued.
* `stream_id` is a client bearer capability (the same value the Manager uses), so public states never
  contain it. `owner` is reduced to `client_id`. `ClientViews` is self-reported by the client, so its
  `client_id` is a consistency label, not authentication. When the injected registry exposes
  `view_for`, that label is authoritative for matching create/capture/rebind; a connected stream without
  a reported view is refused rather than trusting a supplied `client_id`. Server authentication remains
  B3's responsibility.
* Lease deadlines and state coalescing use an injected monotonic clock, never wall time. A lost stream
  gets a grace period to re-bind with the same lease. Expiry marks the capture `interrupted`, clears the
  lease, and publishes a small durable `recorder.state` event; the owner client must stop its microphone
  when it sees it. Expiry never renews capture permission.
* A stop writes its intent (lease hash and final sample count) to the sidecar before sealing, so a crash
  between those steps leaves a retryable stop rather than an unauthenticated stopped recording.
* State-event failures are persisted in the recording sidecar as a one-event outbox and retried by
  `sweep`/startup. Deletions write a bounded tombstone before removing the recording; the tombstone is
  removed only after `recorder.deleted` is published. A successfully committed audio mutation or
  deletion is never turned into an error by an event-bus outage.
* Event delivery is **at-least-once**, not exactly-once. Consumers must dedupe `recorder.state` by
  `(id, revision)` and `recorder.deleted` by `(id, generation)`; a crash after publish but before
  clearing the sidecar/tombstone republishes the same event.
* Unresolved B3 blocker: if the sidecar outbox write itself fails **and** the bus publish also fails,
  the state event remains only in memory and is lost on restart. The committed store state and public
  snapshot remain authoritative and startup reconciliation announces the recovered state, but B2 does
  not claim that individual event is durable. A store-backed transactional outbox is required for a
  fail-closed announcement contract. The deletion tombstone is stricter: `delete` refuses to start if
  its tombstone cannot be written. The deletion outbox is capped at `MAX_DELETED_TOMBSTONES` and refuses
  overflow.
* After expiry (or a stop that declared more audio than was acknowledged) the original client may use
  its own recovery capability to seal its final sample count and upload already-spooled chunks. Recovery
  is bounded by that sealed count by the store; it cannot append new capture.

* A create replay is gated on the client capability, not on the idempotency key alone. A lookup-only
  `resume` never creates: an unknown key is withdrawn in a bounded in-memory set so a create still in
  flight for that key is refused instead of producing a second recording. Because both handlers are
  serialized on the recorder worker, the withdraw either precedes the create or observes it. A
  withdrawal lasts for the rest of the process lifetime: there is no provable upper bound on when a
  queued or slowly delivered create request can still arrive, so a TTL would reopen the duplicate
  window. The set is capped at `MAX_WITHDRAWN_KEYS`; once full it stays full and every new create with no
  registered idempotency entry fails closed (`create_guard_full`) for the rest of the process lifetime.
  That is an explicit availability trade-off: enough distinct unproven lookups deny new starts until Core
  restarts. The set is memory-only because a Core restart terminates every in-flight connection and
  therefore every create that could still arrive.

No PCM, transcript text, lease token, recovery token or stream id is ever placed in a durable event or
in a public snapshot. Events are global (`session_id=None`): `recorder.state`, `recorder.segment` and
`recorder.deleted`. `recorder.segment` is live-only (`durable=False`) for every status, so transcript
text does not enter the global durable event log or outlive recording deletion. The durable transcript
store is C's authority and is not implemented here.

Scheduler discovery: `enumerate_recordings(after, limit)` returns one id-ordered cursor page of
metadata for every recording, including stopped recordings that `reconcile_all` skips. It uses only
`limit + 1` directory candidates and one page of metadata at a time, reports unreadable recordings as
`{id, error}`, and exposes no audio, transcript text, tokens or stream ids. Pages are stable under
deletion and strict id ordering; a concurrently created id below the cursor needs a fresh scan.

Scheduler seam (C3a-S): after durable work the service signals an injected scheduler with
`scheduler.audio_committed(rid, generation, durable_offset)`, `capture_ended(rid, generation, end, state)`,
`recovered(ids)` and the existing `cancel(rid)`. Hooks are synchronous and must only merge state and wake
the loop; they run on the recorder thread while the service lock is held, must not call back into the
service, and every hook exception is logged without changing the capture result. These notifications are
not a durability guarantee: a hook may fail or be missed, so the C3 scheduler must periodically reconcile
persisted capture/transcript state as its safety net. Idempotent stop/recover-stop retries re-signal
`capture_ended` after authentication and final-count checks. Transcription state/progress is exposed
separately through `set_transcription_progress` and `recorder.state`; it is in-memory until C3b re-derives
it from the durable transcript log on restart.

Integration seam: the daemon must call :meth:`RecorderService.sweep` periodically (for expiry and to
flush coalesced/pending state and deletion events), call :meth:`RecorderService.startup` and fail closed
on its `recorder_startup_failed` error, and pass this service's
:meth:`RecorderService.on_stream_detached` to the server's stream registry
(`ClientViews.on_detach`). `create` only starts capture after an explicit user action; nothing here
touches sessions, the Manager or the microphone.

Not provided here (B3/C): HTTP routes, request authentication and body limits; nonblocking event-loop
integration; and the durable transcript revision/query layer. This service is synchronous and may
fsync, so B3 must invoke it off the event loop (threadpool) and bridge its thread-safe bus publishes to
the async stream delivery (`Bus` is publish-locked, but loop delivery/backpressure remains B3's). C owns
durable segment records and query; `publish_segment` only delivers live notifications and does not
persist transcript text. State and deletion events are the B2 events this service retries.
"""
