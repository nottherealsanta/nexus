    def delete(self, recording_id: str) -> bool:
        """Delete a stopped/interrupted recording and its scheduled work; active capture is refused."""
        with self._lock:
            self._ensure_started_locked()
            self._sweep_locked(self._monotonic_now())
            try:
                state = self.store.get(recording_id)
            except RecorderNotFound:
                self._forget(recording_id)
                return False
            except RecorderError:
                # A corrupt/unreadable recording is still the user's data and must be deletable. It cannot
                # be an active capture unless this service knows a lease for it.
                record = self._records.get(recording_id)
                if record is not None and record.active:
                    raise RecorderServiceError(
                        RECORDING_ACTIVE, "stop the active recording before deleting it", status=409) from None
                document = (record.last_document if record is not None and record.last_document is not None
                            else {"id": recording_id, "generation": record.generation if record else 1})
            else:
                document = _doc(state)
                record = self._record_for(recording_id, document)
                if record.active:
                    raise RecorderServiceError(
                        RECORDING_ACTIVE, "stop the active recording before deleting it", status=409)
            if self.bus is not None:
                try:
                    self._write_tombstone(recording_id, int(document.get("generation", 1)))
                except OSError as exc:
                    raise RecorderServiceError(
                        DELETE_NOT_DURABLE,
                        "the deletion tombstone could not be persisted; the recording was not deleted",
                        status=503) from exc
            if self.scheduler is not None and hasattr(self.scheduler, "cancel"):
                try:
                    self.scheduler.cancel(recording_id)
                except Exception:  # a scheduler failure must not leave a half-deleted active-looking job
                    log.warning("recorder scheduler cancel failed for %s", recording_id, exc_info=True)
            deleted = self.store.delete(recording_id)
            self._forget(recording_id)
            if deleted:
                self._process_tombstones_locked()
            else:
                self._remove_tombstone_best_effort(recording_id)
            return deleted

    def sweep(self) -> list[dict[str, Any]]:
        """Expire due leases and flush coalesced state. The daemon should call this periodically."""
        with self._lock:
            self._ensure_started_locked()
            return self._sweep_locked(self._monotonic_now())

    def on_stream_detached(self, stream_id: str) -> bool:
        """Start the detach grace for the active owner stream. A reconnect re-binds with the lease."""
        if not isinstance(stream_id, str):
            return False
        with self._lock:
            self._ensure_started_locked()
            if self._active is None:
                return False
            record = self._records.get(self._active)
            if record is None or not record.active or record.stream_id != stream_id:
                return False
            if record.detached_at is None:
                record.detached_at = self._monotonic_now()
            return True

