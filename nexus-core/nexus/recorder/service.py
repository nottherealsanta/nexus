    def publish_segment(
        self,
        recording_id: str,
        *,
        segment_id: int,
        revision: int,
        start: int,
        end: int,
        status: str,
        text: str,
        generation: int | None = None,
    ) -> dict[str, Any] | None:
        """Publish one revisioned transcript segment as a live-only event.

        Every status, including `final` and `error`, is delivered with `durable=False`: transcript text
        must not enter the global durable event log or survive recording deletion. The scheduler owns
        segment production and C owns the durable transcript store/query; this seam only enforces the
        live event contract and bounds.
        """
        segment_id = _integer(segment_id, "segment_id", maximum=MAX_SEGMENT_ID)
        revision = _integer(revision, "revision")
        start = _integer(start, "start")
        end = _integer(end, "end")
        if end < start:
            raise RecorderServiceError(BAD_REQUEST, "segment end must not precede its start", status=400)
        if status not in SEGMENT_STATUSES:
            raise RecorderServiceError(BAD_REQUEST, "unknown segment status", status=400)
        if not isinstance(text, str) or len(text) > MAX_SEGMENT_TEXT:
            raise RecorderServiceError(
                BAD_REQUEST, f"segment text must be a string of at most {MAX_SEGMENT_TEXT} characters",
                status=400)
        with self._lock:
            self._ensure_started_locked()
            state = self.store.get(recording_id)
            document = _doc(state)
            recording_generation = int(document.get("generation", 1))
            if generation is not None and generation != recording_generation:
                return None
            record = self._record_for(recording_id, document)
            data = {
                "id": recording_id,
                "generation": recording_generation,
                "segment_id": segment_id,
                "revision": revision,
                "start": start,
                "end": end,
                "status": status,
                "text": text,
            }
            if self.bus is not None:
                self.bus.publish("recorder.segment", data, session_id=None, durable=False)
            return {**data, "recording_revision": record.revision}

    # -- internals -------------------------------------------------------------------------------------------

    def _scheduler_hook(self, name: str, *args: Any) -> None:
        """Call one scheduler signal hook; a broken scheduler never affects capture or commits.

        The scheduler contract is synchronous and non-blocking (it merges under its own lock and queues one
        loop wake) and it must not call back into this service from the hook. This method deliberately
        swallows and logs everything else. Hook delivery is not durable; C3 must periodically reconcile
        persisted capture/transcript state, and idempotent stop retries re-signal `capture_ended`.
        """
        scheduler = self.scheduler
        if scheduler is None:
            return
        hook = getattr(scheduler, name, None)
        if not callable(hook):
            return
        try:
            hook(*args)
        except Exception:
            log.warning("recorder scheduler %s hook failed", name, exc_info=True)

    def _now(self) -> float:
        return float(self.clock())

    def _monotonic_now(self) -> float:
        return float(self.monotonic())

    def _ensure_started_locked(self) -> list[dict[str, Any]]:
        if self._started:
            return []
        recovered: list[dict[str, Any]] = []
        try:
            results = self.store.reconcile_all()
            for item in results:
                recording_id = item.get("id")
                if not isinstance(recording_id, str):
                    continue
                if "error" in item:
                    log.warning("recorder recovery for %s failed: %s", recording_id, item.get("error"))
                    continue
                try:
                    state = self.store.get(recording_id)
                except RecorderError:
                    continue
                document = _doc(state)
                if document.get("capture_state") != "interrupted":
                    continue
                record = self._record_for(recording_id, document)
                # No lease survives a restart: a stale token can never append audio again.
                record.lease_hash = None
                record.lease_token = None
                record.stream_id = None
                record.detached_at = None
                record.expires_at = 0.0
                record.capture_override = None
                try:
                    self._publish_state_locked(record, state, force=True, reason="recovered")
                except Exception:
                    log.warning("recorder recovery state event failed for %s", recording_id, exc_info=True)
                recovered.append(self._public(record, state))
            self._load_idempotency_locked()
            self._flush_pending_locked(self._monotonic_now())
            self._process_tombstones_locked()
            recovered_ids = [str(item["id"]) for item in results
                             if isinstance(item.get("id"), str) and "error" not in item]
            self._scheduler_hook("recovered", recovered_ids)
        except Exception as exc:
            # Do not mark the service started and do not let any caller mutate an unreconciled store.
            # The next operation retries; the host sees this failure and can fail closed.
            log.warning("recorder startup reconciliation failed; no capture operations are accepted",
                        exc_info=True)
            raise RecorderServiceError(
                STARTUP_FAILED,
                "recorder startup reconciliation failed; capture operations are unavailable until it succeeds",
                status=503,
            ) from exc
        self._started = True
        return recovered

    def _recording_ids(self) -> list[str]:
        try:
            entries = list(os.scandir(self.store.root))
        except (FileNotFoundError, NotADirectoryError):
            return []
        return sorted(entry.name for entry in entries
                      if entry.is_dir(follow_symlinks=False)
                      and _RECORDING_ID.fullmatch(entry.name) is not None)

    def _load_idempotency_locked(self) -> None:
        """Register persisted create keys and pending state outbox entries.

        The create key hash lives in `meta.json` from the same atomic create as the recording identity, so
        a crash before the service sidecar is written still leaves an idempotent create. The sidecar can
        also carry the key for older recordings and carries the durable pending state event. Loading is
        bounded by the recordings this Core owns; nothing secret is read or exposed.
        """
        for recording_id in self._recording_ids():
            if recording_id in self._records:
                continue
            sidecar = self._read_sidecar(recording_id)
            try:
                creation = self.store.creation_hashes(recording_id)
            except (RecorderError, OSError):
                creation = {}
            if (not isinstance(creation.get("idempotency_sha256"), str)
                    and not (sidecar is not None
                             and isinstance(sidecar.get("idempotency_sha256"), str))
                    and not (sidecar is not None
                             and isinstance(sidecar.get("pending_event"), dict))):
                continue
            try:
                state = self.store.get(recording_id)
            except (RecorderError, OSError):
                continue
            self._record_for(recording_id, _doc(state))

    def _load_idempotency_entry_locked(
        self, key_hash: str) -> tuple[str, str, str | None, str] | None:
        """Find one persisted create by its key hash without creating anything.

        Startup normally registers every keyed recording. This bounded directory scan is the fallback
        for a create whose metadata is durable but whose registration was missed; it is never allowed to
        create a recording or mint a capability.
        """
        for recording_id in self._recording_ids():
            record = self._records.get(recording_id)
            if record is not None:
                if record.idempotency_hash == key_hash:
                    entry = self._idempotent.get(key_hash)
                    if entry is None:
                        # The key is persisted but its client capability is not; creating again could
                        # duplicate the recording, so refuse rather than guess.
                        raise RecorderServiceError(
                            IDEMPOTENCY_CONFLICT,
                            "this idempotency key has no client recovery capability; it cannot be replayed",
                            status=409)
                    return entry
                continue
            try:
                creation = self.store.creation_hashes(recording_id)
            except (RecorderError, OSError):
                continue
            if creation.get("idempotency_sha256") != key_hash:
                continue
            if not isinstance(creation.get("recovery_sha256"), str):
                raise RecorderServiceError(
                    IDEMPOTENCY_CONFLICT,
                    "this idempotency key has no client recovery capability; it cannot be replayed",
                    status=409)
            try:
                state = self.store.get(recording_id)
            except (RecorderError, OSError):
                continue
            self._record_for(recording_id, _doc(state))
            entry = self._idempotent.get(key_hash)
            if entry is not None:
                return entry
        return None

    def _withdraw_locked(self, key_hash: str) -> bool:
        """Withdraw a lookup-only key for this process lifetime.

        Returns False when the bounded set cannot remember it. A withdrawal is never forgotten early:
        a queued or slowly delivered create has no provable arrival bound, so expiring the set would
        reopen the duplicate window.
        """
        if key_hash in self._withdrawn:
            return True
        if self._withdrawn_full or len(self._withdrawn) >= MAX_WITHDRAWN_KEYS:
            # Keep every existing key and deny every new create for the rest of the process. Evicting
            # the oldest withdrawal could let its still-arriving create duplicate a recording.
            self._withdrawn_full = True
            return False
        self._withdrawn.add(key_hash)
        return True

    def _require_create_guard_locked(self, key_hash: str) -> None:
        """Refuse a create that a lookup-only resume may already have declared absent."""
        if key_hash in self._withdrawn:
            raise RecorderServiceError(
                CREATE_WITHDRAWN,
                "this idempotency key was withdrawn by a resume lookup; start with a new key",
                status=409)
        if self._withdrawn_full:
            raise RecorderServiceError(
                CREATE_GUARD_FULL,
                "the recorder cannot safely distinguish this start from a resumed lookup; "
                "new starts are closed until Core restarts",
                status=503)

    def _record_for(self, recording_id: str, document: dict[str, Any]) -> _Lease:
        record = self._records.get(recording_id)
        if record is not None:
            return record
        sidecar = self._read_sidecar(recording_id)
        try:
            creation = self.store.creation_hashes(recording_id)
        except (RecorderError, OSError):
            creation = {}
        owner = document.get("owner") or {}
        generation = int(document.get("generation", 1))
        client_id = ""
        recovery_hash = creation.get("recovery_sha256") or None
        idempotency_hash = creation.get("idempotency_sha256") or None
        stop_sha256 = None
        stop_final = None
        revision = 0
        pending_event = None
        if sidecar is not None and sidecar.get("generation") == generation:
            client_id = str(sidecar.get("client_id") or "")
            recovery_hash = recovery_hash or sidecar.get("recovery_sha256")
            stop_sha256 = sidecar.get("stop_sha256")
            stop_final = sidecar.get("stop_final_sample_count")
            idempotency_hash = idempotency_hash or sidecar.get("idempotency_sha256")
            revision = int(sidecar.get("revision", 0))
            pending_event = sidecar.get("pending_event")
        elif isinstance(owner.get("client_id"), str):
            client_id = owner["client_id"]
        record = _Lease(
            recording_id=recording_id,
            generation=generation,
            client_id=client_id,
            stream_id=None,
            recovery_hash=recovery_hash if isinstance(recovery_hash, str) else None,
            stop_sha256=stop_sha256 if isinstance(stop_sha256, str) else None,
            stop_final_sample_count=stop_final if type(stop_final) is int else None,
            idempotency_hash=idempotency_hash if isinstance(idempotency_hash, str) else None,
            revision=max(0, revision),
        )
        if isinstance(pending_event, dict):
            record.pending_event = pending_event
            record.state_pending = True
            record.pending_reason = pending_event.get("reason")
            self._pending_states.add(recording_id)
        if record.idempotency_hash is not None:
            title = document.get("title") if isinstance(document.get("title"), str) else None
            if isinstance(record.recovery_hash, str):
                self._idempotent.setdefault(
                    record.idempotency_hash, (recording_id, record.client_id, title, record.recovery_hash))
            else:
                # A persisted key without a client capability cannot be replayed or proven. Withdraw it
                # permanently for this process so a create can never duplicate its recording.
                self._withdraw_locked(record.idempotency_hash)
        self._records[recording_id] = record
        return record

    def _registry_client(self, stream_id: str) -> str | None:
        """The registry's self-reported client label for a stream, never a caller-supplied one.

        `ClientViews` exposes both `has_stream` and `view_for`; when the latter exists its `client_id` is
        the consistency label used for matching and a connected stream without a reported view is
        refused. It is not authentication: a minimal injected registry without `view_for` can only be
        checked for connectivity, and the real server must authenticate requests in B3.
        """
        if self.streams is None:
            return None
        if hasattr(self.streams, "has_stream") and not self.streams.has_stream(stream_id):
            raise RecorderServiceError(
                STREAM_CLOSED, "the event stream is not connected; reconnect first", status=409)
        if hasattr(self.streams, "view_for"):
            view = self.streams.view_for(stream_id)
            if not isinstance(view, dict):
                raise RecorderServiceError(
                    STREAM_UNBOUND,
                    "the event stream has no reported client label; report its view and retry",
                    status=409)
            client_id = view.get("client_id")
            if not isinstance(client_id, str) or not _IDENTIFIER.fullmatch(client_id):
                raise RecorderServiceError(
                    STREAM_UNBOUND, "the event stream's client label is invalid", status=409)
            return client_id
        return None

    def _require_lease(self, record: _Lease, lease: str, *, client_id: str | None = None) -> None:
        if not record.active:
            raise RecorderServiceError(LEASE_EXPIRED, "the capture lease is no longer valid", status=409)
        if not _matches(lease, record.lease_hash):
            raise RecorderServiceError(INVALID_LEASE, "the capture lease is invalid", status=403)
        if client_id is not None and record.client_id and client_id != record.client_id:
            raise RecorderServiceError(NOT_OWNER, "this client does not own the recording", status=403)

    def _require_active(
        self,
        record: _Lease,
        lease: str,
        *,
        stream_id: str | None = None,
        client_id: str | None = None,
    ) -> None:
        self._require_lease(record, lease, client_id=client_id)
        bound_stream = record.stream_id
        if stream_id is not None:
            if bound_stream is not None and stream_id != bound_stream:
                raise RecorderServiceError(NOT_OWNER, "this event stream is not the one bound to the capture", status=403)
            bound_stream = stream_id
        if record.detached_at is not None:
            # The caller reports the detach and the documented grace/rebind path; the registry no longer
            # has the old stream, so do not turn the expected detach into a generic stream_closed error.
            return
        if bound_stream is not None:
            registry_client = self._registry_client(bound_stream)
            if registry_client is not None and registry_client != record.client_id:
                raise RecorderServiceError(
                    NOT_OWNER, "the event stream reports a different client label", status=403)

    def _require_recovery(self, record: _Lease, token: str, client_id: str,
                          *, stream_id: str | None = None) -> None:
        if not record.recovery_hash:
            raise RecorderServiceError(
                RECOVERY_UNAVAILABLE, "this recording has no recoverable spool capability", status=403)
        if not _matches(token, record.recovery_hash):
            raise RecorderServiceError(INVALID_LEASE, "the recovery token is invalid", status=403)
        if record.client_id and client_id != record.client_id:
            raise RecorderServiceError(NOT_OWNER, "this client does not own the recording", status=403)
        if stream_id is not None:
            registry_client = self._registry_client(stream_id)
            if registry_client is not None and registry_client != record.client_id:
                raise RecorderServiceError(
                    NOT_OWNER, "the event stream reports a different client label", status=403)

    def _sweep_locked(self, now: float) -> list[dict[str, Any]]:
        expired = self._expire_due_locked(now)
        self._flush_pending_locked(now)
        self._process_tombstones_locked()
        return expired

    def _expire_due_locked(self, now: float) -> list[dict[str, Any]]:
        if self._active is None:
            return []
        record = self._records.get(self._active)
        if record is None or not record.active:
            self._active = None
            return []
        if now < record.deadline():
            return []
        return [self._expire_locked(record, reason="stream_detached" if record.detached_at is not None
                                    else "lease_expired")]

    def _expire_locked(self, record: _Lease, *, reason: str) -> dict[str, Any]:
        recording_id = record.recording_id
        record.lease_hash = None
        record.lease_token = None
        record.stream_id = None
        record.detached_at = None
        record.expires_at = 0.0
        record.state_pending = False
        record.pending_event = None
        self._pending_states.discard(recording_id)
        if self._active == recording_id:
            self._active = None
        try:
            state: Any = self.store.reconcile(recording_id)
        except Exception:
            log.warning("recorder lease expiry reconciliation failed for %s", recording_id, exc_info=True)
            try:
                state = self.store.get(recording_id)
            except (RecorderError, OSError):
                state = record.last_document or {
                    "id": recording_id,
                    "created_at": "",
                    "owner": {"client_id": record.client_id},
                    "generation": record.generation,
                    "format": {},
                    "capture_state": "interrupted",
                    "final_sample_count": None,
                    "sealed": False,
                    "title": None,
                    "revision": 0,
                    "durable_offset": 0,
                    "durable_bytes": 0,
                    "chunks": 0,
                    "next_sequence": 0,
                    "holes": [],
                    "problems": [],
                }
        document = _doc(state)
        record.capture_override = "interrupted" if document.get("capture_state") == "recording" else None
        self._publish_state_locked(record, state, force=True, reason=reason)
        end_offset = document.get("final_sample_count")
        if end_offset is None:
            end_offset = document.get("durable_offset", 0)
        capture_state = record.capture_override or str(document.get("capture_state", "interrupted"))
        self._scheduler_hook(
            "capture_ended", recording_id, int(document.get("generation", record.generation)),
            int(end_offset), capture_state)
        return self._public(record, state)

    def _flush_pending_locked(self, now: float) -> None:
        if self.bus is None or not self._pending_states:
            return
        for recording_id in sorted(self._pending_states)[:MAX_PENDING_STATES]:
            record = self._records.get(recording_id)
            if record is None or not record.state_pending:
                self._pending_states.discard(recording_id)
                continue
            if record.pending_event is not None:
                # Retry the event a failed bus publish left behind; do not replace it with a later state
                # until this one has been delivered or superseded by a forced transition.
                try:
                    self.bus.publish("recorder.state", record.pending_event,
                                     session_id=None, durable=True)
                except Exception:
                    log.warning("recorder state publish still failing for %s", recording_id, exc_info=True)
                    continue
                record.pending_event = None
                record.state_pending = False
                record.pending_reason = None
                self._pending_states.discard(recording_id)
                self._write_sidecar_best_effort(record)
                continue
            if record.last_state_at is not None and now - record.last_state_at < STATE_MIN_INTERVAL_SECONDS:
                continue
            try:
                state = self.store.get(recording_id)
            except RecorderError:
                self._pending_states.discard(recording_id)
                record.state_pending = False
                continue
            self._publish_state_locked(record, state, force=False, reason=record.pending_reason)

    def _process_tombstones_locked(self) -> None:
        """Complete durable deletions and publish their events, then remove each tombstone.

        A tombstone is written before `store.delete`, so a crash can leave either a still-present
        recording or a missing one; both are safe to finish here. Delivery is at-least-once: a crash
        after publish but before tombstone removal republishes the same `(id, generation)`, so
        consumers must dedupe deletions. The outbox is capped at `MAX_DELETED_TOMBSTONES`; `delete`
        refuses to start another deletion when it is full.
        """
        if self.bus is None:
            return
        for path in self._tombstone_paths()[:MAX_DELETED_TOMBSTONES]:
            tombstone = self._read_tombstone(path)
            if tombstone is None:
                log.warning("recorder deletion tombstone is unreadable: %s", path.name)
                continue
            recording_id, generation = tombstone
            record = self._records.get(recording_id)
            if record is not None and record.active:
                # A deletion intent for an active capture is not completed implicitly.
                continue
            try:
                self.store.delete(recording_id)
            except (RecorderError, OSError):
                log.warning("recorder tombstone deletion failed for %s", recording_id, exc_info=True)
                continue
            self._forget(recording_id)
            # At-least-once: a crash after this publish and before unlink republishes the same
            # (id, generation); consumers must treat duplicate deletions as no-ops.
            data = {"id": recording_id, "generation": generation}
            try:
                self.bus.publish("recorder.deleted", data, session_id=None, durable=True)
            except Exception:
                log.warning("recorder deleted event publish still failing for %s", recording_id,
                            exc_info=True)
                return
            try:
                path.unlink()
                _fsync_dir(path.parent)
            except FileNotFoundError:
                pass
            except OSError:
                log.warning("recorder tombstone cleanup failed for %s", recording_id, exc_info=True)

    def _publish_state_locked(
        self,
        record: _Lease,
        state: Any,
        *,
        force: bool,
        reason: str | None = None,
    ) -> dict[str, Any] | None:
        now = self._monotonic_now()
        if (not force and record.pending_event is None and record.last_state_at is not None
                and now - record.last_state_at < STATE_MIN_INTERVAL_SECONDS):
            record.state_pending = True
            if reason is not None:
                record.pending_reason = reason
            self._pending_states.add(record.recording_id)
            return None
        document = self._observe(record, state)
        record.revision += 1
        record.last_state_at = now
        data: dict[str, Any] = {
            "id": record.recording_id,
            "generation": int(document.get("generation", record.generation)),
            "revision": record.revision,
            "capture_state": document.get("capture_state", "interrupted"),
            "transcription_state": record.transcription_state,
            "transcription": {
                "state": record.transcription_state,
                "progress": dict(record.transcription_progress),
            },
            "transcription_progress": dict(record.transcription_progress),
            "transcript_revision": record.transcription_progress.get("transcript_revision"),
            "active": record.active,
            "durable_offset": int(document.get("durable_offset", 0)),
            "durable_bytes": int(document.get("durable_bytes", 0)),
            "chunks": int(document.get("chunks", 0)),
            "final_sample_count": document.get("final_sample_count"),
            "title": document.get("title"),
            "complete": self._complete(document),
            "holes": len(document.get("holes") or []),
            "lag_seconds": None,
        }
        if reason is not None:
            data["reason"] = reason
        if self.bus is None:
            record.pending_event = None
            record.state_pending = False
            record.pending_reason = None
            self._pending_states.discard(record.recording_id)
            self._write_sidecar_best_effort(record)
            return None
        # Best-effort durable state outbox: persist the exact event before publishing. A crash after this
        # write republishes the same revision on startup (consumers dedupe by id+revision). If this write
        # and the bus publish both fail, the event below is memory-only and is lost on restart; the
        # committed store state remains authoritative for snapshots/startup reconciliation.
        record.pending_event = data
        record.state_pending = True
        record.pending_reason = reason
        self._pending_states.add(record.recording_id)
        self._write_sidecar_best_effort(record)
        try:
            event = self.bus.publish("recorder.state", data, session_id=None, durable=True)
        except Exception:
            log.warning("recorder state event publish failed for %s", record.recording_id, exc_info=True)
            return None
        record.pending_event = None
        record.state_pending = False
        record.pending_reason = None
        self._pending_states.discard(record.recording_id)
        self._write_sidecar_best_effort(record)
        return event

    def _observe(self, record: _Lease, state: Any) -> dict[str, Any]:
        document = _doc(state)
        if record.capture_override is not None:
            document["capture_state"] = record.capture_override
        record.last_document = dict(document)
        return document

    @staticmethod
    def _complete(document: dict[str, Any]) -> bool:
        final = document.get("final_sample_count")
        return (bool(document.get("sealed")) and final is not None
                and int(document.get("durable_offset", 0)) >= int(final)
                and not document.get("holes"))

    def _public(self, record: _Lease, state: Any) -> dict[str, Any]:
        document = dict(self._observe(record, state))
        owner = document.get("owner") or {}
        client_id = owner.get("client_id")
        document["owner"] = {"client_id": client_id} if isinstance(client_id, str) else {}
        document.pop("free_seconds", None)
        now = self._monotonic_now()
        document["active"] = record.active
        document["stream_detached"] = record.detached_at is not None if record.active else False
        document["lease_expires_in"] = (
            round(max(0.0, record.deadline() - now), 3) if record.active else None)
        document["event_revision"] = record.revision
        document["transcription_state"] = record.transcription_state
        document["transcription"] = {
            "state": record.transcription_state,
            "progress": dict(record.transcription_progress),
        }
        document["transcription_progress"] = dict(record.transcription_progress)
        document["transcript_revision"] = record.transcription_progress.get("transcript_revision")
        document["complete"] = self._complete(document)
        final = document.get("final_sample_count")
        document["missing_samples"] = (
            max(0, int(final) - int(document.get("durable_offset", 0))) if final is not None else None)
        return document

    def _create_response(
        self,
        record: _Lease,
        state: Any,
        *,
        replayed: bool,
        free_seconds: float | None = None,
    ) -> dict[str, Any]:
        document = self._public(record, state)
        document["lease_token"] = record.lease_token if record.active else None
        document["lease"] = document["lease_token"]  # the name used by the transport (`X-Recorder-Lease`)
        # Core never holds the client capability, so it can never return it; the marker tells a stale
        # client that expected a Core-generated token to fail loudly instead of spooling nothing.
        document["recovery_token"] = None
        document["recovery"] = "client"
        document["idempotent"] = replayed
        document["replay_state"] = "active" if record.active else document["capture_state"]
        document["recoverable"] = False
        document["tokens_reissued"] = bool(replayed and record.active)
        if free_seconds is None:
            try:
                free_seconds = self.store.free_seconds()
            except OSError:
                free_seconds = None
        document["free_seconds"] = free_seconds
        return document

    def _replay_response(self, record: _Lease, state: Any) -> dict[str, Any]:
        """An idempotent create replay whose raw tokens are no longer safe to reissue.

        The recording is already interrupted/stopped (an active lease would have been replayed above).
        We return the authoritative public snapshot and an explicit marker; recovery uses the capability
        the client generated and persisted itself, never one minted or re-exposed by Core.
        """
        document = self._public(record, state)
        document["lease_token"] = None
        document["lease"] = None
        document["recovery_token"] = None
        document["recovery"] = "client"
        document["idempotent"] = True
        document["replay_state"] = document["capture_state"]
        document["recoverable"] = bool(
            document["capture_state"] == "interrupted"
            or (not document["sealed"] and not document["active"])
            or (document["sealed"] and not document["complete"]))
        document["tokens_reissued"] = False
        try:
            document["free_seconds"] = self.store.free_seconds()
        except OSError:
            document["free_seconds"] = None
        return document

    def _release_active(self, record: _Lease) -> None:
        record.lease_hash = None
        record.lease_token = None
        record.stream_id = None
        record.detached_at = None
        record.expires_at = 0.0
        record.state_pending = False
        record.pending_reason = None
        record.pending_event = None
        self._pending_states.discard(record.recording_id)
        if self._active == record.recording_id:
            self._active = None

    def _forget(self, recording_id: str) -> None:
        self._records.pop(recording_id, None)
        self._pending_states.discard(recording_id)
        if self._active == recording_id:
            self._active = None
        for key, entry in list(self._idempotent.items()):
            if entry[0] == recording_id:
                self._idempotent.pop(key, None)

    # -- private sidecar (hash only, never a raw token) -------------------------------------------------------

    def _sidecar_path(self, recording_id: str) -> Path:
        return Path(self.store.root) / recording_id / SIDECAR_NAME

    def _sidecar_document(self, record: _Lease) -> dict[str, Any]:
        return {
            "version": SIDECAR_VERSION,
            "id": record.recording_id,
            "generation": record.generation,
            "client_id": record.client_id,
            "recovery_sha256": record.recovery_hash,
            "stop_sha256": record.stop_sha256,
            "stop_final_sample_count": record.stop_final_sample_count,
            "idempotency_sha256": record.idempotency_hash,
            "pending_event": record.pending_event,
            "revision": record.revision,
        }

    def _atomic_write_private(self, path: Path, payload: bytes) -> None:
        temporary = path.parent / f".{path.name}.{os.getpid()}.{secrets.token_hex(4)}.tmp"
        try:
            fd = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_EXCL
                         | getattr(os, "O_NOFOLLOW", 0), 0o600)
            try:
                os.fchmod(fd, 0o600)
                _write_all(fd, payload)
                os.fsync(fd)
            finally:
                os.close(fd)
            os.replace(temporary, path)
            _fsync_dir(path.parent)
        finally:
            try:
                temporary.unlink()
            except OSError:
                pass

    def _write_sidecar(self, record: _Lease) -> None:
        payload = (json.dumps(self._sidecar_document(record), sort_keys=True,
                              separators=(",", ":"), ensure_ascii=False) + "\n").encode()
        self._atomic_write_private(self._sidecar_path(record.recording_id), payload)

    def _write_sidecar_best_effort(self, record: _Lease) -> None:
        try:
            self._write_sidecar(record)
        except OSError:
            # Capture and the durable audio range do not depend on the revision/capability hint; a later
            # create/stop writes it again. Never expose the failure as a successful secret-bearing event.
            log.warning("recorder lease sidecar write failed for %s", record.recording_id, exc_info=True)

    @staticmethod
    def _private_directory(path: Path) -> Path:
        """Validate a directory the way the recorder store does: owned 0700, not a symlink."""
        info = path.lstat()
        if stat.S_ISLNK(info.st_mode) or not stat.S_ISDIR(info.st_mode):
            raise RecorderSecurityError(
                "directory_unsafe", f"recorder directory is not a real directory: {path}")
        if info.st_uid != os.getuid():
            raise RecorderSecurityError(
                "directory_owner", f"recorder directory is not owned by this user: {path}")
        if stat.S_IMODE(info.st_mode) != 0o700:
            raise RecorderSecurityError(
                "directory_mode", f"recorder directory must be mode 0700: {path}")
        return path

    def _outbox_dir(self) -> Path:
        root = self._private_directory(Path(self.store.root))
        path = root / OUTBOX_DIR
        try:
            path.lstat()
        except FileNotFoundError:
            os.mkdir(path, 0o700)
            os.chmod(path, 0o700)
            _fsync_dir(root)
        return self._private_directory(path)

    def _tombstone_paths(self) -> list[Path]:
        directory = Path(self.store.root) / OUTBOX_DIR
        try:
            self._private_directory(directory)
        except FileNotFoundError:
            return []
        except RecorderSecurityError:
            log.warning("recorder deletion outbox has unsafe ownership or mode; refusing to read it")
            return []
        except OSError:
            log.warning("recorder deletion outbox cannot be validated; refusing to read it", exc_info=True)
            return []
        try:
            entries = list(os.scandir(directory))
        except OSError:
            return []
        return sorted(Path(entry.path) for entry in entries
                      if entry.is_file(follow_symlinks=False)
                      and entry.name.endswith(".json")
                      and _RECORDING_ID.fullmatch(entry.name[:-5]) is not None)

    def _write_tombstone(self, recording_id: str, generation: int) -> None:
        directory = self._outbox_dir()
        path = directory / f"{recording_id}.json"
        if not path.exists() and len(self._tombstone_paths()) >= MAX_DELETED_TOMBSTONES:
            raise OSError("recorder deletion outbox is full")
        payload = (json.dumps({
            "version": TOMBSTONE_VERSION,
            "id": recording_id,
            "generation": int(generation),
        }, sort_keys=True, separators=(",", ":")) + "\n").encode()
        self._atomic_write_private(path, payload)

    def _read_tombstone(self, path: Path) -> tuple[str, int] | None:
        recording_id = path.stem
        try:
            fd = os.open(path, os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0))
        except OSError:
            return None
        try:
            info = os.fstat(fd)
            if not stat.S_ISREG(info.st_mode) or info.st_size > MAX_TOMBSTONE_BYTES:
                return None
            if info.st_uid != os.getuid() or stat.S_IMODE(info.st_mode) != 0o600:
                return None
            chunks: list[bytes] = []
            remaining = info.st_size
            while remaining > 0:
                block = os.read(fd, min(remaining, MAX_TOMBSTONE_BYTES))
                if not block:
                    break
                chunks.append(block)
                remaining -= len(block)
            payload = json.loads(b"".join(chunks))
        except (OSError, ValueError):
            return None
        finally:
            os.close(fd)
        if (not isinstance(payload, dict) or payload.get("version") != TOMBSTONE_VERSION
                or payload.get("id") != recording_id
                or type(payload.get("generation")) is not int):
            return None
        return recording_id, payload["generation"]

    def _remove_tombstone_best_effort(self, recording_id: str) -> None:
        path = Path(self.store.root) / OUTBOX_DIR / f"{recording_id}.json"
        try:
            path.unlink()
            _fsync_dir(path.parent)
        except FileNotFoundError:
            pass
        except OSError:
            log.warning("recorder tombstone cleanup failed for %s", recording_id, exc_info=True)

    def _read_sidecar(self, recording_id: str) -> dict[str, Any] | None:
        path = self._sidecar_path(recording_id)
        try:
            fd = os.open(path, os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0))
        except (FileNotFoundError, NotADirectoryError, PermissionError):
            return None
        except OSError:
            log.warning("recorder lease sidecar could not be opened for %s", recording_id, exc_info=True)
            return None
        try:
            info = os.fstat(fd)
            if not stat.S_ISREG(info.st_mode) or info.st_size > MAX_SIDECAR_BYTES:
                return None
            chunks: list[bytes] = []
            remaining = info.st_size
            while remaining > 0:
                block = os.read(fd, min(remaining, 64 * 1024))
                if not block:
                    break
                chunks.append(block)
                remaining -= len(block)
            payload = json.loads(b"".join(chunks))
        except (OSError, ValueError):
            log.warning("recorder lease sidecar is unreadable for %s", recording_id)
            return None
        finally:
            os.close(fd)
        if not isinstance(payload, dict) or payload.get("version") != SIDECAR_VERSION:
            return None
        if payload.get("id") != recording_id:
            return None
        if type(payload.get("generation")) is not int or type(payload.get("revision")) is not int:
            return None
        client_id = payload.get("client_id")
        if not isinstance(client_id, str) or len(client_id) > MAX_CLIENT_ID:
            return None
        recovery = payload.get("recovery_sha256")
        stop_hash = payload.get("stop_sha256")
        if recovery is not None and (not isinstance(recovery, str) or not _SHA256.fullmatch(recovery)):
            return None
        if stop_hash is not None and (not isinstance(stop_hash, str) or not _SHA256.fullmatch(stop_hash)):
            return None
        stop_final = payload.get("stop_final_sample_count")
        if stop_final is not None and (type(stop_final) is not int or stop_final < 0):
            return None
        idempotency = payload.get("idempotency_sha256")
        if idempotency is not None and (not isinstance(idempotency, str)
                                        or not _SHA256.fullmatch(idempotency)):
            return None
        pending_event = payload.get("pending_event")
        if pending_event is not None and not isinstance(pending_event, dict):
            return None
        return payload
