//! nexus-design-mockup: static TUI mock-ups for DESIGN_PLAN.md.
//!   cargo run -- list                       every shot id
//!   cargo run -- screen <id> [dark|light|mono] [--ascii]   print one shot as text
//!   cargo run -- shoot [--only <prefix>]    ../shots/tui/<id>-<mode>.{svg,txt}
//!   cargo run -- css                        ../nsh/tokens.css from ../theme.toml
#![allow(dead_code)]
mod kit;
mod screens;
mod shell;
mod svg;
mod theme;

use ratatui::{buffer::Buffer, layout::Rect};
use std::{fs, path::Path};
use theme::{Mode, Th};

fn render(s: &screens::Shot, mode: Mode, ascii: bool) -> Buffer {
    let mut t = Th::new(mode);
    t.ascii = ascii;
    screens::alt::palette(s.id, &mut t);
    let mut buf = Buffer::empty(Rect::new(0, 0, s.w, s.h));
    let mut p = kit::P::new(&mut buf, &t);
    p.fill(0, 0, s.w, s.h, "surface.canvas");
    (s.draw)(&mut p);
    buf
}

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let flag = |n: &str| args.iter().position(|a| a == n).and_then(|i| args.get(i + 1)).cloned();
    let shots = screens::all();
    match args.first().map(String::as_str) {
        Some("list") => {
            for s in &shots {
                println!("{:<34} {:>3}x{:<3} {}", s.id, s.w, s.h, s.caption);
            }
        }
        Some("screen") => {
            let id = args.get(1).cloned().unwrap_or_default();
            let mode = args.get(2).and_then(|m| Mode::parse(m)).unwrap_or(Mode::Dark);
            let Some(s) = shots.iter().find(|s| s.id == id) else {
                eprintln!("unknown shot {id}; try `list`");
                std::process::exit(2)
            };
            print!("{}", svg::to_text(&render(s, mode, args.iter().any(|a| a == "--ascii"))));
        }
        Some("shoot") => {
            let only = flag("--only");
            let out = Path::new("../shots/tui");
            fs::create_dir_all(out).unwrap();
            let mut n = 0;
            for s in shots.iter().filter(|s| only.as_ref().map(|o| s.id.starts_with(o.as_str())).unwrap_or(true)) {
                for &mode in s.modes {
                    let mut t = Th::new(mode);
                    screens::alt::palette(s.id, &mut t);
                    let buf = render(s, mode, false);
                    let (fg, bg) = t.page();
                    let stem = format!("{}-{}", s.id, mode.name());
                    fs::write(out.join(format!("{stem}.svg")), svg::to_svg(&buf, fg, &bg)).unwrap();
                    fs::write(out.join(format!("{stem}.txt")), svg::to_text(&buf)).unwrap();
                    n += 1;
                }
                if s.ascii {
                    let buf = render(s, Mode::Dark, true);
                    let (fg, bg) = Th::new(Mode::Dark).page();
                    fs::write(out.join(format!("{}-ascii.svg", s.id)), svg::to_svg(&buf, fg, &bg)).unwrap();
                    n += 1;
                }
            }
            fs::write(Path::new("../shots/tui/manifest.tsv"), shots.iter().map(|s| format!("{}\t{}\t{}\t{}\n", s.id, s.w, s.h, s.caption)).collect::<String>()).unwrap();
            println!("wrote {n} shots to ../shots/tui");
        }
        Some("css") => {
            fs::write("../nsh/tokens.css", css()).unwrap();
            println!("wrote ../nsh/tokens.css");
        }
        _ => println!("usage: list | screen <id> [dark|light|mono] [--ascii] | shoot [--only prefix] | css"),
    }
}

/// CSS custom properties for the NSH mock-ups: `--surface-canvas`, `--text-muted`…
fn css() -> String {
    let doc: toml::Table = theme::SOURCE.parse().unwrap();
    let mut out = String::from("/* Generated by `cargo run -- css` from ../theme.toml. Do not edit. */\n");
    for (sel, palette) in [(":root, [data-theme=dark]", "dark"), ("[data-theme=light]", "light")] {
        out.push_str(&format!("{sel} {{\n"));
        if let Some(toml::Value::Table(groups)) = doc.get(palette) {
            for (g, vals) in groups {
                if let toml::Value::Table(vals) = vals {
                    for (k, v) in vals {
                        if let Some(s) = v.as_str() {
                            out.push_str(&format!("  --{g}-{}: {s};\n", k.replace('_', "-")));
                        }
                    }
                }
            }
        }
        out.push_str("}\n");
    }
    out
}
